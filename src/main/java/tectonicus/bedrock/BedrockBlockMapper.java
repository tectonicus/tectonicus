package tectonicus.bedrock;

import lombok.extern.slf4j.Slf4j;
import org.jnbt.ByteTag;
import org.jnbt.CompoundTag;
import org.jnbt.IntTag;
import org.jnbt.ShortTag;
import org.jnbt.StringTag;
import org.jnbt.Tag;
import tectonicus.raw.BlockProperties;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.concurrent.ConcurrentHashMap;
import java.util.zip.GZIPInputStream;

/**
 * Converts Bedrock Edition block states into Java Edition block names and properties, using the table generated by
 * {@code SourceData/bedrock/generate_bedrock_mappings.py}. A state missing from the table, usually because a newer
 * or older Bedrock version added or removed a state, takes the Java state of the closest listed state of that block.
 */
@Slf4j
public final class BedrockBlockMapper {
	private static final String RESOURCE = "/bedrock/blocks.tsv.gz";
	private static final Set<String> CHESTS = Set.of("minecraft:chest", "minecraft:trapped_chest");

	/** A Java block state. {@code waterloggable} is true when Java has a waterlogged property for it. */
	public record JavaState(String name, BlockProperties properties, boolean waterloggable) {
		public JavaState withProperty(String key, String value) {
			Map<String, String> props = new TreeMap<>(properties.getProperties());
			props.put(key, value);
			return new JavaState(name, new BlockProperties(props), waterloggable);
		}
	}

	private record Candidate(Map<String, String> states, String java) {}

	private static volatile BedrockBlockMapper instance;

	private final Map<String, String> table;
	private final Map<String, List<Candidate>> byName = new HashMap<>();
	private final Map<String, JavaState> cache = new ConcurrentHashMap<>();
	private final Set<String> reported = ConcurrentHashMap.newKeySet();

	BedrockBlockMapper(Map<String, String> table) {
		this.table = table;
		for (Map.Entry<String, String> entry : table.entrySet()) {
			String key = entry.getKey();
			byName.computeIfAbsent(name(key), k -> new ArrayList<>()).add(new Candidate(parseProperties(key), entry.getValue()));
		}
	}

	public static BedrockBlockMapper get() {
		BedrockBlockMapper mapper = instance;
		if (mapper == null) {
			synchronized (BedrockBlockMapper.class) {
				mapper = instance;
				if (mapper == null) {
					mapper = new BedrockBlockMapper(load());
					instance = mapper;
				}
			}
		}
		return mapper;
	}

	private static Map<String, String> load() {
		Map<String, String> table = new HashMap<>(32768);
		try (InputStream raw = BedrockBlockMapper.class.getResourceAsStream(RESOURCE)) {
			if (raw == null)
				throw new IllegalStateException("Missing resource " + RESOURCE);
			try (BufferedReader reader = new BufferedReader(new InputStreamReader(new GZIPInputStream(raw), StandardCharsets.UTF_8))) {
				String line;
				while ((line = reader.readLine()) != null) {
					if (line.isEmpty() || line.startsWith("#"))
						continue;
					int tab = line.indexOf('\t');
					if (tab > 0)
						table.put(line.substring(0, tab), line.substring(tab + 1));
				}
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
		log.debug("Loaded {} Bedrock block states", table.size());
		return table;
	}

	/** Maps one palette entry: a compound with {@code name} and a {@code states} compound. */
	public JavaState map(CompoundTag paletteEntry) {
		return map(key(paletteEntry));
	}

	/** Maps a Bedrock state written as {@code name[key=value,...]} with its keys sorted. */
	public JavaState map(String bedrockKey) {
		return cache.computeIfAbsent(bedrockKey, this::resolve);
	}

	private JavaState resolve(String key) {
		String java = table.get(key);
		if (java == null) {
			java = closest(key);
			if (reported.add(name(key)))
				log.debug("No exact Java mapping for Bedrock state {}; using {}", key, java);
		}
		String name = name(java);
		Map<String, String> props = parseProperties(java);
		boolean waterloggable = props.containsKey("waterlogged");
		if (CHESTS.contains(name) && props.containsKey("type"))
			props.put("type", "single"); // The block entity says which half a double chest is
		return new JavaState(name, new BlockProperties(props), waterloggable);
	}

	private String closest(String key) {
		String name = name(key);
		List<Candidate> candidates = byName.get(name);
		if (candidates == null) {
			if (reported.add(name))
				log.warn("Unknown Bedrock block {}; rendering it under the same name", name);
			return name + "[]";
		}
		Map<String, String> wanted = parseProperties(key);
		Candidate best = candidates.getFirst();
		int bestScore = -1;
		for (Candidate candidate : candidates) {
			int score = 0;
			for (Map.Entry<String, String> state : wanted.entrySet()) {
				if (state.getValue().equals(candidate.states().get(state.getKey())))
					score++;
			}
			if (score > bestScore) {
				best = candidate;
				bestScore = score;
			}
		}
		return best.java();
	}

	/** The Bedrock block's name, such as {@code minecraft:stone}. */
	public static String bedrockName(CompoundTag paletteEntry) {
		Tag name = paletteEntry.getValue().get("name");
		return name instanceof StringTag string ? normalizeName(string.getValue()) : "minecraft:air";
	}

	/** Writes a palette entry as {@code name[key=value,...]} with sorted keys, the form the table is keyed by. */
	public static String key(CompoundTag paletteEntry) {
		StringBuilder key = new StringBuilder(bedrockName(paletteEntry)).append('[');
		Tag states = paletteEntry.getValue().get("states");
		if (states instanceof CompoundTag compound && !compound.getValue().isEmpty()) {
			boolean first = true;
			for (Map.Entry<String, Tag> state : new TreeMap<>(compound.getValue()).entrySet()) {
				if (!first)
					key.append(',');
				first = false;
				key.append(state.getKey()).append('=').append(value(state.getValue()));
			}
		}
		return key.append(']').toString();
	}

	private static String normalizeName(String name) {
		return name.indexOf(':') < 0 ? "minecraft:" + name : name;
	}

	private static String value(Tag tag) {
		return switch (tag) {
			case ByteTag b -> Integer.toString(b.getValue());
			case ShortTag s -> Integer.toString(s.getValue());
			case IntTag i -> Integer.toString(i.getValue());
			case StringTag s -> s.getValue();
			default -> String.valueOf(tag.getValue());
		};
	}

	private static String name(String state) {
		int bracket = state.indexOf('[');
		return bracket < 0 ? state : state.substring(0, bracket);
	}

	private static Map<String, String> parseProperties(String state) {
		Map<String, String> props = new LinkedHashMap<>();
		int open = state.indexOf('[');
		if (open < 0 || state.length() - open <= 2)
			return props;
		for (String pair : state.substring(open + 1, state.length() - 1).split(",")) {
			int eq = pair.indexOf('=');
			if (eq > 0)
				props.put(pair.substring(0, eq), pair.substring(eq + 1));
		}
		return props;
	}
}
