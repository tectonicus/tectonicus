package tectonicus.bedrock;

import lombok.extern.slf4j.Slf4j;
import org.tectonicus.jnbt.ByteTag;
import org.tectonicus.jnbt.CompoundTag;
import org.tectonicus.jnbt.IntTag;
import org.tectonicus.jnbt.ShortTag;
import org.tectonicus.jnbt.StringTag;
import org.tectonicus.jnbt.Tag;
import tectonicus.blockregistry.EmissiveBlock;
import tectonicus.raw.BlockProperties;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Consumer;
import java.util.zip.GZIPInputStream;

/**
 * Converts Bedrock Edition block states into Java Edition block names and properties, using the table generated by
 * {@code SourceData/bedrock/generate_bedrock_mappings.py}. A state missing from the table, usually because a newer
 * or older Bedrock version added or removed a state, takes the Java state of the closest listed state of that block.
 */
@Slf4j
public final class BedrockBlockMapper {
	private static final String RESOURCE = "/bedrock/blocks.tsv.gz";
	private static final String LEGACY_RESOURCE = "/bedrock/legacy.tsv.gz";
	private static final Set<String> CHESTS = Set.of("minecraft:chest", "minecraft:trapped_chest");

	/**
	 * A Java block state. {@code waterloggable} is true when Java has a waterlogged property for it; {@code opacity}
	 * (0 to 15) and {@code emission} (0 to 15) are the light the block takes away and gives out.
	 */
	public record JavaState(String name, BlockProperties properties, boolean waterloggable, int opacity, int emission) {
		public static JavaState of(String name, BlockProperties properties, boolean waterloggable) {
			EmissiveBlock emissive = EmissiveBlock.forBlockName(name);
			return new JavaState(name, properties, waterloggable, SkyLight.opacity(name, properties),
					emissive == null ? 0 : emissive.getLightEmission(properties.getProperties()));
		}

		public JavaState withProperty(String key, String value) {
			Map<String, String> props = new TreeMap<>(properties.getProperties());
			props.put(key, value);
			return of(name, new BlockProperties(props), waterloggable);
		}

		public String get(String property) {
			return properties.get(property);
		}

		public boolean isAir() {
			return name.equals("minecraft:air") || name.equals("minecraft:cave_air") || name.equals("minecraft:void_air");
		}
	}

	private record Candidate(Map<String, String> states, String java) {}

	private static volatile BedrockBlockMapper instance;

	private final Map<String, String> table;
	/** States by Bedrock name and data value, such as {@code minecraft:fence:5}, for palettes saved before 1.13. */
	private final Map<String, String> legacy;
	private final Map<String, List<Candidate>> byName = new HashMap<>();
	private final Map<String, JavaState> cache = new ConcurrentHashMap<>();
	private final Map<JavaState, JavaState> waterlogged = new ConcurrentHashMap<>();
	private final Set<String> reported = ConcurrentHashMap.newKeySet();

	BedrockBlockMapper(Map<String, String> table) {
		this(table, Map.of());
	}

	BedrockBlockMapper(Map<String, String> table, Map<String, String> legacy) {
		this.table = table;
		this.legacy = legacy;
		for (Map.Entry<String, String> entry : table.entrySet()) {
			String key = entry.getKey();
			byName.computeIfAbsent(name(key), k -> new ArrayList<>()).add(new Candidate(parseProperties(key), entry.getValue()));
		}
	}

	public static BedrockBlockMapper get() {
		BedrockBlockMapper mapper = instance;
		if (mapper == null) {
			synchronized (BedrockBlockMapper.class) {
				mapper = instance;
				if (mapper == null) {
					mapper = new BedrockBlockMapper(load(), loadLegacy());
					instance = mapper;
				}
			}
		}
		return mapper;
	}

	private static Map<String, String> load() {
		Map<String, String> table = new HashMap<>(32768);
		readTable(RESOURCE, line -> {
			int tab = line.indexOf('\t');
			if (tab > 0)
				table.put(line.substring(0, tab), line.substring(tab + 1));
		});
		log.debug("Loaded {} Bedrock block states", table.size());
		return table;
	}

	private static Map<String, String> loadLegacy() {
		Map<String, String> legacy = new HashMap<>(8192);
		readTable(LEGACY_RESOURCE, line -> {
			String[] parts = line.split("\t");
			if (parts.length == 3)
				legacy.put(parts[0] + ':' + parts[1], parts[2]);
		});
		return legacy;
	}

	private static void readTable(String resource, Consumer<String> lines) {
		try (InputStream raw = BedrockBlockMapper.class.getResourceAsStream(resource)) {
			if (raw == null)
				throw new IllegalStateException("Missing resource " + resource);
			try (BufferedReader reader = new BufferedReader(new InputStreamReader(new GZIPInputStream(raw), StandardCharsets.UTF_8))) {
				String line;
				while ((line = reader.readLine()) != null) {
					if (!line.isEmpty() && !line.startsWith("#"))
						lines.accept(line);
				}
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	/**
	 * Maps one palette entry: a compound with {@code name} and a {@code states} compound, or, in worlds saved by
	 * Bedrock 1.2.13 to 1.12, a {@code val} data value instead of the states.
	 */
	public JavaState map(CompoundTag paletteEntry) {
		Tag val = paletteEntry.getValue().get("val");
		if (val != null && !(paletteEntry.getValue().get("states") instanceof CompoundTag states && !states.getValue().isEmpty())) {
			String name = bedrockName(paletteEntry);
			int data = BedrockItems.number(val, 0);
			String key = legacy.get(name + ':' + data);
			if (key == null)
				key = legacy.get(name + ":0"); // A data value the block does not use
			if (key != null)
				return map(key);
		}
		return map(key(paletteEntry));
	}

	/** Maps a Bedrock state written as {@code name[key=value,...]} with its keys sorted. */
	public JavaState map(String bedrockKey) {
		return cache.computeIfAbsent(bedrockKey, this::resolve);
	}

	/** The same state with water in it, shared between blocks so each distinct state is one object. */
	public JavaState waterlogged(JavaState state) {
		return waterlogged.computeIfAbsent(state, s -> s.withProperty("waterlogged", "true"));
	}

	private JavaState resolve(String key) {
		JavaState special = special(key);
		if (special != null)
			return special;
		String java = table.get(key);
		if (java == null && key.contains("torch_facing_direction=unknown"))
			java = table.get(key.replace("torch_facing_direction=unknown", "torch_facing_direction=top")); // A standing torch
		if (java == null) {
			java = closest(key);
			if (reported.add(name(key)))
				log.debug("No exact Java mapping for Bedrock state {}; using {}", key, java);
		}
		String name = name(java);
		Map<String, String> props = parseProperties(java);
		boolean waterloggable = props.containsKey("waterlogged");
		if (CHESTS.contains(name) && props.containsKey("type"))
			props.put("type", "single"); // The block entity says which half a double chest is
		return JavaState.of(name, new BlockProperties(props), waterloggable);
	}

	/**
	 * Blocks the table maps wrongly or that Java does not have. Item frames are blocks in Bedrock and entities in Java,
	 * so they keep a placeholder name with their facing until the chunk reader turns them into entities. A flower pot's
	 * plant is in its block entity.
	 */
	private static JavaState special(String key) {
		String name = name(key);
		return switch (name) {
			case "minecraft:frame", "minecraft:glow_frame" -> {
				String facing = FACINGS[Math.floorMod(Integer.parseInt(parseProperties(key).getOrDefault("facing_direction", "2")), 6)];
				yield JavaState.of(name.equals("minecraft:frame") ? ITEM_FRAME : GLOW_ITEM_FRAME,
						new BlockProperties(Map.of("facing", facing)), false);
			}
			case "minecraft:flower_pot" -> JavaState.of("minecraft:flower_pot", new BlockProperties(), false);
			default -> null;
		};
	}

	/** Placeholder names for item frames, which the chunk reader replaces with air and an entity. */
	public static final String ITEM_FRAME = "tectonicus:item_frame";
	public static final String GLOW_ITEM_FRAME = "tectonicus:glow_item_frame";
	/** Directions by Bedrock's facing_direction and Java's 3D direction index. */
	public static final String[] FACINGS = {"down", "up", "north", "south", "west", "east"};

	private String closest(String key) {
		String name = name(key);
		List<Candidate> candidates = byName.get(name);
		if (candidates == null) {
			if (reported.add(name))
				log.warn("Unknown Bedrock block {}; rendering it under the same name", name);
			return name + "[]";
		}
		Map<String, String> wanted = parseProperties(key);
		Candidate best = candidates.getFirst();
		int bestScore = -1;
		for (Candidate candidate : candidates) {
			int score = 0;
			for (Map.Entry<String, String> state : wanted.entrySet()) {
				if (state.getValue().equals(candidate.states().get(state.getKey())))
					score++;
			}
			if (score > bestScore) {
				best = candidate;
				bestScore = score;
			}
		}
		return best.java();
	}

	/** The Bedrock block's name, such as {@code minecraft:stone}. */
	public static String bedrockName(CompoundTag paletteEntry) {
		Tag name = paletteEntry.getValue().get("name");
		return name instanceof StringTag string ? normalizeName(string.getValue()) : "minecraft:air";
	}

	/** Writes a palette entry as {@code name[key=value,...]} with sorted keys, the form the table is keyed by. */
	public static String key(CompoundTag paletteEntry) {
		StringBuilder key = new StringBuilder(bedrockName(paletteEntry)).append('[');
		Tag states = paletteEntry.getValue().get("states");
		if (states instanceof CompoundTag compound && !compound.getValue().isEmpty()) {
			boolean first = true;
			for (Map.Entry<String, Tag> state : new TreeMap<>(compound.getValue()).entrySet()) {
				if (!first)
					key.append(',');
				first = false;
				key.append(state.getKey()).append('=').append(value(state.getValue()));
			}
		}
		return key.append(']').toString();
	}

	private static String normalizeName(String name) {
		return name.indexOf(':') < 0 ? "minecraft:" + name : name;
	}

	private static String value(Tag tag) {
		return switch (tag) {
			case ByteTag b -> Integer.toString(b.getValue());
			case ShortTag s -> Integer.toString(s.getValue());
			case IntTag i -> Integer.toString(i.getValue());
			case StringTag s -> s.getValue();
			default -> String.valueOf(tag.getValue());
		};
	}

	private static String name(String state) {
		int bracket = state.indexOf('[');
		return bracket < 0 ? state : state.substring(0, bracket);
	}

	private static Map<String, String> parseProperties(String state) {
		Map<String, String> props = new LinkedHashMap<>();
		int open = state.indexOf('[');
		if (open < 0 || state.length() - open <= 2)
			return props;
		for (String pair : state.substring(open + 1, state.length() - 1).split(",")) {
			int eq = pair.indexOf('=');
			if (eq > 0)
				props.put(pair.substring(0, eq), pair.substring(eq + 1));
		}
		return props;
	}
}
